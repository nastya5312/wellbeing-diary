// Все пороги анализа в одном месте (ТЗ, раздел 7.6). Менять только осознанно.

/** Минимум заполненных дней, чтобы показывать любые выводы. Меньше — экран «Прогресс данных». */
export const MIN_COMPLETED_DAYS = 30;
/** Минимум дней с фактором (a + b) в таблице. */
export const MIN_FACTOR_DAYS = 5;
/** Минимум совпадений (a). */
export const MIN_COINCIDENCES = 3;
/** Отношение рисков: показываем «чаще» при RR ≥ 1.5 и «реже» при RR ≤ 0.67. */
export const RR_HIGH = 1.5;
export const RR_LOW = 0.67;
/** Порог q-значения (после поправки на множественные сравнения). */
export const Q_MAX = 0.25;

/**
 * Категории силы сигнала.
 * В ТЗ: «заметный» q ≤ 0,10, «сильный» q ≤ 0,05. Ужесточено после проверки на случайных данных:
 * при q ≤ 0,10 ложный «заметный» сигнал появлялся примерно в 1 наборе из 15 (сценарий B).
 * При q ≤ 0,02 / 0,005 настоящая связь из сценария A по-прежнему находится как «сильная».
 * Порог «слабого сигнала» (Q_MAX = 0,25) оставлен как в ТЗ.
 */
export const NOTABLE = { q: 0.02, rr: 2 };
export const STRONG = { q: 0.005, rr: 3, a: 5 };

/** Числовые пары (Спирмен): минимум пар и порог |rho|. */
export const MIN_PAIRS = 20;
export const RHO_MIN = 0.35;

/**
 * Проверка перемешиванием (сверх ТЗ). Записи идут сериями: плохие дни подряд, привычки неделями.
 * Обычные тесты считают дни независимыми и поэтому чаще находят случайные совпадения.
 * Сдвигаем ряд результата по кругу и смотрим, как часто совпадение получается не хуже настоящего.
 */
export const PERMUTATIONS = 400;
export const PERM_P_MAX = 0.1;

/** Окно «перед месячными»: дни −1…−5 до начала следующего цикла. */
export const PREMENSTRUAL_DAYS = 5;
/** Если следующего начала нет дольше этого срока, «перед месячными» не определяем. */
export const MAX_CYCLE_LOOKAHEAD = 45;

/**
 * Воспроизводимость (сверх ТЗ): «заметный» и «сильный» сигнал должен повторяться в обеих половинах
 * периода по отдельности — с тем же направлением и отношением рисков не слабее этого порога.
 * Без этого на случайных данных примерно 1 набор из 10 даёт ложный «заметный» сигнал
 * (порог q ≤ 0,10 допускает 10% ложных находок).
 */
export const REPLICATION_RR = 1.25;
export const REPLICATION_MIN_A = 2;

/** Совпадающие факторы (7.7): phi, с которого показывается предупреждение */
export const PHI_CONFOUND = 0.5;
/** Минимум дней с фактором в каждой страте для пересчёта */
export const MIN_STRATUM_F_DAYS = 3;
/** Сколько совпадающих факторов показывать у одного вывода */
export const MAX_CONFOUNDS = 3;

/** Окна интервалов после лекарства — только для сравнения дней, не рекомендация */
export const GAP_FOOD_MIN = 60;
export const GAP_SUPPLEMENT_MIN = 240;
