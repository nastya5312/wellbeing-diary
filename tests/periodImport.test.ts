import { describe, it, expect } from 'vitest';
import { parsePeriodText } from '../src/lib/periodImport';

// Полностью выдуманная сводка в формате отчёта «Трекер периодов» (от новых циклов к старым)
const REPORT = `Имя: Тест Возраст: 30

Сводка по циклу 5 июня,2019 - 10 марта (5 циклы)

История циклов 5 июня,2019 - 10 марта

2 февр. - Сегодня 4 Дня

5 янв. - 1 февр. 5 Дней 28 Дней

Трекер Периодов Страница 1/99

9 дек.,2021 - 4 янв. 6 Дней 27 Дней

10 нояб.,2021 - 8 дек.,2021 2 Дня 29 Дней

12 окт.,2021 - 9 нояб.,2021 10 Дней 29 Дней

Сведения о цикле

2 февр. - Сегодня (36 Дней)

5 янв. - 1 февр. (28 Дней) След. шаг 28-28 Дней \\>\\>`;

describe('импорт месячных', () => {
  it('сводка отчёта: годы восстанавливаются, число дней берётся из отчёта, детальные страницы игнорируются', () => {
    const r = parsePeriodText(REPORT, '2022-03-10');
    expect(r.periods).toEqual([
      { start: '2021-10-12', days: 10 },
      { start: '2021-11-10', days: 2 },
      { start: '2021-12-09', days: 6 },
      { start: '2022-01-05', days: 5 },
      { start: '2022-02-02', days: 4 },
    ]);
    expect(r.skipped).toEqual([]);
  });

  it('сверка длины цикла: совпадает у всех строк; расхождение считается', () => {
    const r = parsePeriodText(REPORT, '2022-03-10');
    expect(r.checked).toBe(4);
    expect(r.lengthMismatches).toBe(0);
    const bad = parsePeriodText('2 февр. - Сегодня 4 Дня\n5 янв. - 1 февр. 5 Дней 30 Дней', '2022-03-10');
    expect(bad.lengthMismatches).toBe(1);
  });

  it('год без явного указания берётся по предыдущей строке, при пересечении границы года — на год раньше', () => {
    const r = parsePeriodText('3 янв. - 30 янв. 5 Дней 28 Дней\n6 дек. - 2 янв. 5 Дней 28 Дней', '2023-02-01');
    expect(r.periods.map((p) => p.start)).toEqual(['2022-12-06', '2023-01-03']);
  });

  it('простые строки: «2022-01-05 5» и «05.01.2022 5»', () => {
    const r = parsePeriodText('2022-02-02 4\n05.01.2022; 5\nзаголовок', '2022-03-10');
    expect(r.periods).toEqual([{ start: '2022-01-05', days: 5 }, { start: '2022-02-02', days: 4 }]);
  });

  it('повтор даты не дублируется; мусор не мешает', () => {
    const r = parsePeriodText('2022-02-02 4\n2022-02-02 4\nСтраница 3\n', '2022-03-10');
    expect(r.periods).toHaveLength(1);
  });
});
